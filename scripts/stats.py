#!/usr/bin/env python
"""Paired statistics for the manuscript: bootstrap confidence intervals and Holm-corrected
Wilcoxon signed-rank tests on per-block SER, pairing receivers on (seed, block), i.e. on the
same channel realisation and the same noise/attack draw.

    python scripts/stats.py            # writes docs/STATS.md and prints it

Cells: attack window (blocks 30-69) of the E3 white-box grid at SIR -10/0/10 dB and of the
transfer grid at 0 dB; clean 100-block runs of E2 at 10 dB (cosine, Jakes); 8x8 at SIR 0;
Doppler 0.05; COST2100 relative-slack SIR 0; nonlinear SIR 0. Every table is regenerated from
the JSON records; nothing is typed by hand.
"""
from __future__ import annotations

import glob
import json
import os
from collections import defaultdict

import numpy as np
from scipy.stats import wilcoxon

RX = ["lmmse", "online_deepsic", "meta_deepsic", "drift_deepsic", "medbn_deepsic", "titans_single", "citadel"]
LABEL = {"lmmse": "LMMSE", "online_deepsic": "Online DeepSIC", "meta_deepsic": "Meta-DeepSIC",
         "drift_deepsic": "Drift-detection", "medbn_deepsic": "MedBN-style", "titans_single": "Single-memory Titans",
         "citadel": "Citadel-Rx"}
rng = np.random.default_rng(0)


def load(folder):
    out = []
    for fn in glob.glob(os.path.join(folder, "*.json")):
        r = json.load(open(fn))
        out.append(r)
    return out


def per_block(recs, select, window):
    """{receiver: {(seed, block): ser}} over the records that satisfy select(config)."""
    d = defaultdict(dict)
    for r in recs:
        c = r["config"]
        if not select(c):
            continue
        rt = c["receiver"]["type"]
        for b in r["blocks"]:
            if window is None or window[0] <= b["block"] < window[1]:
                d[rt][(r["seed"], b["block"])] = b["ser"]
    return d


def boot_ci(x, n=10000):
    x = np.asarray(x)
    m = rng.choice(x, size=(n, x.size), replace=True).mean(1)
    return float(x.mean()), float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))


def paired_table(d, ref="citadel", title=""):
    """Mean SER with bootstrap CI per receiver, and paired Citadel-minus-baseline tests."""
    rows = [f"**{title}**", "", "| receiver | mean SER [95% CI] | n (seed,block) pairs | Δ (Citadel − receiver) [95% CI] | Wilcoxon p (Holm) |", "|---|---|---|---|---|"]
    if ref not in d:
        return "\n".join(rows + ["| (no Citadel records) | | | | |"])
    base = d[ref]
    pvals, lines = [], []
    for rt in RX:
        if rt not in d:
            continue
        keys = sorted(set(base) & set(d[rt]))
        x = np.array([d[rt][k] for k in keys])
        m, lo, hi = boot_ci(x)
        if rt == ref:
            lines.append((rt, f"| {LABEL[rt]} | {m:.4f} [{lo:.4f}, {hi:.4f}] | {len(keys)} | – | – |", None))
            continue
        diff = np.array([base[k] - d[rt][k] for k in keys])
        dm, dlo, dhi = boot_ci(diff)
        p = wilcoxon(diff, zero_method="wilcox").pvalue if np.any(diff != 0) else 1.0
        pvals.append(p)
        lines.append((rt, f"| {LABEL[rt]} | {m:.4f} [{lo:.4f}, {hi:.4f}] | {len(keys)} | {dm:+.4f} [{dlo:+.4f}, {dhi:+.4f}] |", p))
    # Holm correction over the comparisons of this table
    order = np.argsort(pvals)
    holm = {}
    m_ = len(pvals)
    running = 0.0
    for rank, idx in enumerate(order):
        adj = min(1.0, (m_ - rank) * pvals[idx])
        running = max(running, adj)
        holm[idx] = running
    j = 0
    for rt, line, p in lines:
        if p is None:
            rows.append(line)
        else:
            rows.append(line + f" {holm[j]:.2e} |" if holm[j] >= 1e-3 else line + f" <0.001 |")
            j += 1
    return "\n".join(rows)


def main():
    e3 = load("results/e3"); e2 = load("results/e2"); e8 = load("results/e8"); e9 = load("results/e9")
    e3rel = load("results/e3rel"); e3cost = load("results/e3cost"); e3nl = load("results/e3nl")
    W = (30, 70)
    out = ["# Paired statistics (regenerated by scripts/stats.py)", "",
           "Pairs are (seed, block): every receiver sees the same channel realisation, noise and attack draw. "
           "CIs: 10 000-resample bootstrap of the mean over pairs. Tests: two-sided Wilcoxon signed-rank on the paired "
           "differences, Holm-corrected within each table. Attack window = blocks 30–69.", ""]
    for sir in (-10, 0, 10):
        d = per_block(e3, lambda c: c["attack"]["type"] == "a1" and c["attack"]["knowledge"] == "whitebox" and c["attack"]["sir_db"] == sir
                      and c["receiver"]["type"] != "lmmse", W)   # LMMSE has no adaptation map: its valid attacked row is the transfer one
        out.append(paired_table(d, title=f"White-box A1, SIR {sir} dB, linear 4x4, 10 dB, attack window")); out.append("")
    d = per_block(e3, lambda c: c["attack"]["type"] == "a1" and c["attack"]["knowledge"] == "transfer" and c["attack"]["sir_db"] == 0, W)
    out.append(paired_table(d, title="Transfer A1, SIR 0 dB, attack window")); out.append("")
    d = per_block(e3, lambda c: c["attack"]["type"] == "data_jam", W)
    out.append(paired_table(d, title="Data jamming control, 0 dB, window")); out.append("")
    for fad in ("cosine", "jakes"):
        d = per_block(e2, lambda c: c["attack"]["type"] == "none" and c["channel"]["snr_db"] == 10 and c["channel"]["fading"] == fad, None)
        out.append(paired_table(d, title=f"Clean, {fad} fading, 10 dB, all 100 blocks")); out.append("")
    d = per_block(e8, lambda c: c["attack"]["type"] == "a1" and c["attack"]["sir_db"] == 0 and c["receiver"]["type"] != "lmmse", W)
    out.append(paired_table(d, title="8x8, white-box A1, SIR 0 dB, attack window")); out.append("")
    d = per_block(e8, lambda c: c["attack"]["type"] == "none", None)
    out.append(paired_table(d, title="8x8, clean, all 100 blocks")); out.append("")
    d = per_block(e9, lambda c: c["channel"]["jakes_fd_tb"] == 0.05 and c["receiver"]["type"] != "lmmse", W)
    out.append(paired_table(d, title="Jakes f_D T_b = 0.05, white-box A1, SIR 0 dB, attack window")); out.append("")
    d = per_block(e3nl, lambda c: c["attack"]["sir_db"] == 0 and c["receiver"]["type"] != "lmmse", W)
    out.append(paired_table(d, title="Nonlinear (tanh PA), white-box A1, SIR 0 dB, attack window")); out.append("")
    d = per_block(e3cost, lambda c: c["attack"]["sir_db"] == 0 and c["receiver"]["type"] != "citadel", W)
    d.update(per_block(e3rel, lambda c: c["channel"]["model"] == "cost2100" and c["attack"]["type"] == "a1" and c["attack"]["sir_db"] == 0, W))
    out.append(paired_table(d, title="COST2100, white-box A1, SIR 0 dB, attack window (Citadel with relative slack)")); out.append("")
    txt = "\n".join(out)
    open("docs/STATS.md", "w").write(txt)
    print(txt)


if __name__ == "__main__":
    main()
