#!/usr/bin/env python
"""Render docs/RESPONSE_TO_REVIEWERS.md from docs/RESPONSE_TO_REVIEWERS.tmpl.md.

Every number in the response letter is a placeholder {{key}} for a value that
scripts/revision_numbers.py wrote to paper/numbers.tex, so the letter and the paper can never
disagree. An unknown key is an error, not a blank.

    python scripts/revision_numbers.py && python scripts/fill_response.py
"""
from __future__ import annotations

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def plain(v: str) -> str:
    """LaTeX value -> plain text: $+0.0193$ -> +0.0193, 2.2\\cdot10^{-4} -> 2.2e-4, \\,dB -> dB."""
    v = v.replace("$", "").replace("\\,", " ").replace("\\%", "%")
    v = re.sub(r"\\cdot\s*10\^\{(-?\d+)\}", r"e\1", v)
    v = v.replace("\\times", "x").replace("{", "").replace("}", "")
    return v.strip()


def main() -> None:
    vals = dict(re.findall(r"\\@namedef\{val@([^}]*)\}\{(.*)\}$", open(os.path.join(ROOT, "paper", "numbers.tex")).read(), re.M))
    tmpl = open(os.path.join(ROOT, "docs", "RESPONSE_TO_REVIEWERS.tmpl.md")).read()
    missing = sorted({k for k in re.findall(r"\{\{([^}]+)\}\}", tmpl) if k not in vals})
    if missing:
        sys.exit("unknown keys: " + ", ".join(missing))
    out = re.sub(r"\{\{([^}]+)\}\}", lambda m: plain(vals[m.group(1)]), tmpl)
    head = ("<!-- generated by scripts/fill_response.py from docs/RESPONSE_TO_REVIEWERS.tmpl.md and paper/numbers.tex;"
            " edit the template -->\n")
    open(os.path.join(ROOT, "docs", "RESPONSE_TO_REVIEWERS.md"), "w").write(head + out)
    print(f"docs/RESPONSE_TO_REVIEWERS.md written ({len(re.findall(r'{{', tmpl))} numbers)")


if __name__ == "__main__":
    main()
